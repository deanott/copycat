//! The cat mark: geometry defined once, rendered two ways.
//!
//! [`CAT`] is a list of primitives in a normalised 0..1 box (x right, y down).
//! [`paint`] draws them with the egui painter for the window header;
//! [`rasterize`] scan-converts the same list to RGBA for the tray and window
//! icons. Defining the geometry once is the point — an icon drawn from its own
//! copy of these numbers drifts the first time either is retuned.
//!
//! [`CAT`] itself is **generated**, by `scripts/logo/build.py` from the master
//! in `scripts/logo/mark.py`. That script also writes the SVG, the Windows
//! `.ico` and the macOS master from the same geometry, which is the only reason
//! those four agree. Edit the master, re-run the script; do not hand-edit here.
//!
//! The mark was a text glyph (`ᓚᘏᗢ`) once, and that could not work: the only
//! widely-shipped face covering all three codepoints draws `ᘏ` as a spiral, and
//! picking a "better" font is no fix either, since the shapes a reader gets
//! depend on whichever face wins the fallback chain on *their* machine. Drawing
//! the mark ourselves is what makes it the same mark everywhere.

use egui::{
    epaint::{CubicBezierShape, PathStroke},
    Color32, Painter, Pos2, Rect, Shape,
};

/// Width / height of the rect the mark is drawn into.
///
/// 1.0 by construction, and deliberately *not* derived from the geometry: the
/// generator fits the ink to a square box (`normaliser` in build.py), because
/// [`paint`] maps that box onto its rect while sizing stroke widths and circle
/// radii off the rect's height alone. Deriving this from the ink's own aspect
/// drew the header cat squashed to 60% of its width.
pub const ASPECT: f32 = 1.0;

/// The mark's ink for the rasterised icons: white.
///
/// GENERATED, like [`CAT`] — `build.py --color` rewrites this, so the Rust
/// rasterisers cannot be repainted independently of the SVG and the .ico.
///
/// Scoped to the icons on purpose. The mark is a thin outline and the surfaces
/// these land on — title bars, taskbars, tray panels — are dark far more often
/// than not, where a tint only muddies a 1–2 px line. The window header is
/// *not* covered: it sits on a surface this app themes itself, so `app.rs`
/// picks its own colour. The one place this is wrong is a light background,
/// where white on transparent is invisible; see the note in
/// `scripts/logo/build.py` for why that is left as a deliberate choice rather
/// than hedged with an outline or a shadow.
pub const INK: [u8; 3] = [0xFF, 0xFF, 0xFF];

/// A piece of the mark, in the normalised 0..1 box.
///
/// Every variant is convex or a stroked curve, and the whole mark is drawn in
/// one flat colour — so the pieces compose into a single silhouette and the
/// draw order between them does not matter.
#[derive(Debug, Clone, Copy)]
pub enum Prim {
    Circle {
        c: (f32, f32),
        r: f32,
    },
    Tri([(f32, f32); 3]),
    /// Cubic bézier centre-line, stroked `w` wide (fraction of height).
    Stroke {
        p: [(f32, f32); 4],
        w: f32,
    },
}

