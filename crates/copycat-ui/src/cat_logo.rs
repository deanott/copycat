/// How many segments the bézier is flattened into for coverage testing.
const BEZIER_STEPS: usize = 48;

impl Prim {
    /// Is the normalised point `(x, y)` inside this primitive?
    fn covers(&self, x: f32, y: f32) -> bool {
        match *self {
            Prim::Circle { c, r } => {
                let (dx, dy) = (x - c.0, y - c.1);
                dx * dx + dy * dy <= r * r
            }
            Prim::Tri(t) => {
                // Inside iff the point is on the same side of all three edges.
                // Comparing signs rather than requiring a winding order means
                // the vertices can be listed either way round.
                let side = |a: (f32, f32), b: (f32, f32)| {
                    (b.0 - a.0) * (y - a.1) - (b.1 - a.1) * (x - a.0)
                };
                let (d0, d1, d2) = (side(t[0], t[1]), side(t[1], t[2]), side(t[2], t[0]));
                let neg = d0 < 0.0 || d1 < 0.0 || d2 < 0.0;
                let pos = d0 > 0.0 || d1 > 0.0 || d2 > 0.0;
                !(neg && pos)
            }
            Prim::Stroke { p, w } => {
                // Flatten the curve and take the distance to the nearest
                // segment — round joins and caps fall out of this for free.
                let half = w / 2.0;
                let mut prev = p[0];
                for i in 1..=BEZIER_STEPS {
                    let t = i as f32 / BEZIER_STEPS as f32;
                    let cur = bezier_at(p, t);
                    if dist_to_seg(x, y, prev, cur) <= half {
                        return true;
                    }
                    prev = cur;
                }
                false
            }
        }
    }
}

/// Cubic bézier evaluated at `t`.
fn bezier_at(p: [(f32, f32); 4], t: f32) -> (f32, f32) {
    let u = 1.0 - t;
    let (a, b, c, d) = (u * u * u, 3.0 * u * u * t, 3.0 * u * t * t, t * t * t);
    (
        a * p[0].0 + b * p[1].0 + c * p[2].0 + d * p[3].0,
        a * p[0].1 + b * p[1].1 + c * p[2].1 + d * p[3].1,
    )
}

/// Distance from `(x, y)` to the segment `s`–`e`.
fn dist_to_seg(x: f32, y: f32, s: (f32, f32), e: (f32, f32)) -> f32 {
    let (vx, vy) = (e.0 - s.0, e.1 - s.1);
    let len2 = vx * vx + vy * vy;
    let t = if len2 <= f32::EPSILON {
        0.0
    } else {
        (((x - s.0) * vx + (y - s.1) * vy) / len2).clamp(0.0, 1.0)
    };
    let (dx, dy) = (x - (s.0 + t * vx), y - (s.1 + t * vy));
    (dx * dx + dy * dy).sqrt()
}

/// Draw the mark filling `rect`, in `color` — the window-header renderer.
pub fn paint(painter: &Painter, rect: Rect, color: Color32) {
    let p = |x: f32, y: f32| {
        Pos2::new(
            rect.left() + x * rect.width(),
            rect.top() + y * rect.height(),
        )
    };
    let h = rect.height();

    for prim in CAT {
        match *prim {
            Prim::Circle { c, r } => painter.add(Shape::circle_filled(p(c.0, c.1), r * h, color)),
            Prim::Tri(t) => painter.add(Shape::convex_polygon(
                t.iter().map(|v| p(v.0, v.1)).collect(),
                color,
                PathStroke::NONE,
            )),
            Prim::Stroke { p: b, w } => {
                let pts = [
                    p(b[0].0, b[0].1),
                    p(b[1].0, b[1].1),
                    p(b[2].0, b[2].1),
                    p(b[3].0, b[3].1),
                ];
                painter.add(CubicBezierShape::from_points_stroke(
                    pts,
                    false,
                    Color32::TRANSPARENT,
                    PathStroke::new(w * h, color),
                ));
                // epaint strokes have butt caps. A dot at each end rounds the
                // stroke off, and where consecutive segments of an outline
                // share an endpoint those same dots become the round join.
                painter.add(Shape::circle_filled(pts[0], w * h / 2.0, color));
                painter.add(Shape::circle_filled(pts[3], w * h / 2.0, color))
            }
        };
    }
}

/// Breathing room around the mark in the rasterised icon, as a fraction of the
/// icon. Tray bars butt icons against their neighbours, so unlike the header —
/// which is laid out with real spacing — the padding has to be baked in.
const ICON_PAD: f32 = 0.06;

/// Supersampling per axis when rasterising. 4×4 is plenty at icon sizes and
/// costs ~16k point tests for a 32² icon, i.e. nothing.
const SUPERSAMPLE: u32 = 4;

/// Scan-convert the mark to `size`×`size` non-premultiplied RGBA — the tray
/// renderer. Anti-aliased by supersampling, so it stays readable at 16–32 px.
pub fn rasterize(size: u32, rgb: [u8; 3]) -> Vec<u8> {
    let mut out = Vec::with_capacity((size * size * 4) as usize);
    let span = 1.0 - 2.0 * ICON_PAD;
    for py in 0..size {
        for px in 0..size {
            let mut hits = 0u32;
            for sy in 0..SUPERSAMPLE {
                for sx in 0..SUPERSAMPLE {
                    // Pixel-centre sampling, mapped into the padded box.
                    let fx = (px as f32 + (sx as f32 + 0.5) / SUPERSAMPLE as f32) / size as f32;
                    let fy = (py as f32 + (sy as f32 + 0.5) / SUPERSAMPLE as f32) / size as f32;
                    let (x, y) = ((fx - ICON_PAD) / span, (fy - ICON_PAD) / span);
                    if CAT.iter().any(|p| p.covers(x, y)) {
                        hits += 1;
                    }
                }
            }
            let alpha = (hits * 255 / (SUPERSAMPLE * SUPERSAMPLE)) as u8;
            out.extend_from_slice(&[rgb[0], rgb[1], rgb[2], alpha]);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rasterize_emits_rgba_of_the_requested_colour() {
        let size = 32;
        let px = rasterize(size, INK);
        assert_eq!(px.len(), (size * size * 4) as usize);
        // Every pixel carries the requested colour; only alpha varies.
        assert!(px.chunks_exact(4).all(|p| [p[0], p[1], p[2]] == INK));
    }

    #[test]
    fn rasterize_is_neither_blank_nor_solid() {
        // An outline, not a silhouette: most of a 32² icon is transparent, and
        // the ink is only the stroke. The lower bound is what catches a mark
        // that failed to generate; the upper bound catches the opposite
        // regression, a `Prim` that fills its interior.
        let px = rasterize(32, [255, 255, 255]);
        let opaque = px.chunks_exact(4).filter(|p| p[3] > 128).count();
        assert!(
            (40..300).contains(&opaque),
            "expected an outline's worth of ink, got {opaque} px of 1024"
        );
    }

    #[test]
    fn rasterize_is_anti_aliased() {
        // Supersampling must produce partial coverage at the edges, otherwise
        // the mark looks jagged in the tray.
        let px = rasterize(32, [255, 255, 255]);
        assert!(px.chunks_exact(4).any(|p| p[3] > 0 && p[3] < 255));
    }

    /// Endpoints of the outline segments, in order. The mark's skeleton.
    fn stroke_ends() -> Vec<((f32, f32), (f32, f32))> {
        CAT.iter()
            .filter_map(|p| match *p {
                Prim::Stroke { p, .. } => Some((p[0], p[3])),
                _ => None,
            })
            .collect()
    }

    #[test]
    fn the_mark_is_a_hollow_outline() {
        // The defining property of this mark: the line is ink, the head it
        // encloses is not. Both probes are derived from the geometry rather
        // than written down, so retuning the mark cannot silently invalidate
        // them the way hardcoded coordinates did.
        let ends = stroke_ends();
        assert!(
            CAT.iter().any(|p| p.covers(ends[0].0 .0, ends[0].0 .1)),
            "the outline's own start point should be on the stroke"
        );
        let n = ends.len() as f32;
        let cx = ends.iter().map(|e| e.0 .0).sum::<f32>() / n;
        let cy = ends.iter().map(|e| e.0 .1).sum::<f32>() / n;
        assert!(
            !CAT.iter()
                .any(|p| matches!(p, Prim::Stroke { .. }) && p.covers(cx, cy)),
            "the middle of the head ({cx}, {cy}) should be enclosed, not inked"
        );
        assert!(
            !CAT.iter().any(|p| p.covers(0.02, 0.02)),
            "corner is margin"
        );
    }

    #[test]
    fn the_face_sits_within_the_outline() {
        // Eyes and nose come from a different part of the master than the
        // outline does, so nothing but this stops them drifting outside it.
        let ends = stroke_ends();
        let (lo, hi) = ends.iter().fold((f32::MAX, f32::MIN), |(lo, hi), e| {
            (lo.min(e.0 .0), hi.max(e.0 .0))
        });
        for prim in CAT {
            let pts: Vec<(f32, f32)> = match *prim {
                Prim::Circle { c, .. } => vec![c],
                Prim::Tri(t) => t.to_vec(),
                Prim::Stroke { .. } => continue,
            };
            for (x, y) in pts {
                assert!((lo..=hi).contains(&x), "face point {x} outside {lo}..{hi}");
                assert!(CAT.iter().any(|p| p.covers(x, y)), "face point is not ink");
            }
        }
    }

    #[test]
    fn every_stroke_is_covered_at_its_midpoint() {
        // Guards the bézier flattening: each curve's own midpoint must fall
        // inside its stroke, which fails if the sampling or the distance test
        // regresses. Every segment, since the outline is a chain of them now
        // rather than the single tail it used to be.
        for (i, prim) in CAT.iter().enumerate() {
            if let Prim::Stroke { p, .. } = *prim {
                let mid = bezier_at(p, 0.5);
                assert!(
                    prim.covers(mid.0, mid.1),
                    "segment {i} does not cover its own midpoint"
                );
            }
        }
    }

    #[test]
    fn the_outline_is_one_unbroken_closed_chain() {
        // Each stroke starts where the previous ended, and the last closes back
        // to the first. The mark is one continuous pen line, so a codegen slip
        // that dropped or reordered a segment shows up as a gap in the drawing
        // rather than as a compile error.
        let ends = stroke_ends();
        for w in ends.windows(2) {
            let (prev, next) = (w[0].1, w[1].0);
            assert!(
                (prev.0 - next.0).abs() < 1e-4 && (prev.1 - next.1).abs() < 1e-4,
                "gap between segments: {prev:?} then {next:?}"
            );
        }
        let (first, last) = (ends[0].0, ends[ends.len() - 1].1);
        assert!(
            (first.0 - last.0).abs() < 1e-4 && (first.1 - last.1).abs() < 1e-4,
            "outline does not close: starts {first:?}, ends {last:?}"
        );
    }

    #[test]
    fn the_mark_fills_its_box() {
        // The generator fits the ink to the box (see `normaliser` in
        // build.py). If that regressed, the mark would sit small and
        // off-centre inside a square rect and every icon would look shrunken —
        // which is exactly what the header showed before it was fixed.
        let ends = stroke_ends();
        let (mut lo, mut hi) = ((f32::MAX, f32::MAX), (f32::MIN, f32::MIN));
        for (a, _) in &ends {
            lo = (lo.0.min(a.0), lo.1.min(a.1));
            hi = (hi.0.max(a.0), hi.1.max(a.1));
        }
        let tall = hi.1 - lo.1;
        assert!(tall > 0.85, "mark spans only {tall} of its box vertically");
        let left = lo.0;
        let right = 1.0 - hi.0;
        assert!(
            (left - right).abs() < 0.05,
            "mark is not centred: {left} left, {right} right"
        );
    }
}
